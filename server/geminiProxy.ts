const withTimeout = async <T>(promise: Promise<T>, timeoutMs: number): Promise<T> => {
  let timeoutId: NodeJS.Timeout | undefined;
  const guarded = promise.catch(() => undefined as unknown as T);
  try {
    return await Promise.race([
      promise,
      new Promise<T>((_, reject) => {
        timeoutId = setTimeout(() => reject(new Error('Timeout')), timeoutMs);
      })
    ]);
  } finally {
    if (timeoutId) clearTimeout(timeoutId);
    void guarded;
  }
};

const getLocalDayKey = () => {
  try {
    const parts = new Intl.DateTimeFormat('en-GB', {
      timeZone: 'Europe/London',
      year: 'numeric',
      month: '2-digit',
      day: '2-digit',
    }).formatToParts(new Date());
    const y = parts.find((p) => p.type === 'year')?.value;
    const m = parts.find((p) => p.type === 'month')?.value;
    const day = parts.find((p) => p.type === 'day')?.value;
    if (y && m && day) return `${y}-${m}-${day}`;
  } catch {
    // ignore
  }
  const d = new Date();
  const y = d.getFullYear();
  const m = String(d.getMonth() + 1).padStart(2, '0');
  const day = String(d.getDate()).padStart(2, '0');
  return `${y}-${m}-${day}`;
};

const isValidDayKey = (value: string | null | undefined): value is string => {
  if (!value || !/^\d{4}-\d{2}-\d{2}$/.test(value)) return false;
  const date = new Date(`${value}T00:00:00Z`);
  return !Number.isNaN(date.getTime()) && date.toISOString().slice(0, 10) === value;
};

const isFresh = (cached: Cached<any> | undefined, ttlMs: number) => {
  if (!cached) return false;
  return now() - cached.updatedAt < ttlMs && cached.dayKey === getLocalDayKey();
};

const normalize = (value: string) => value.trim().replace(/\s+/g, ' ').toLowerCase();

const parseTimeToMinutes = (time: string) => {
  const raw = time.trim().toLowerCase();
  if (!raw) return null;

  const withMinutes = raw.match(/(\d{1,2})\s*[:.]\s*(\d{2})\s*(am|pm)?/i);
  const withoutMinutes = raw.match(/(\d{1,2})\s*(am|pm)/i);

  const hourStr = withMinutes?.[1] ?? withoutMinutes?.[1];
  const minuteStr = withMinutes?.[2] ?? '00';
  const ampm = (withMinutes?.[3] ?? withoutMinutes?.[2] ?? '').toLowerCase();

  if (!hourStr) return null;
  let hours = Number(hourStr);
  const minutes = Number(minuteStr);
  if (!Number.isFinite(hours) || !Number.isFinite(minutes)) return null;
  if (minutes < 0 || minutes > 59) return null;

  if (ampm === 'am') {
    if (hours === 12) hours = 0;
  } else if (ampm === 'pm') {
    if (hours !== 12) hours += 12;
  }

  if (hours < 0 || hours > 23) return null;
  return hours * 60 + minutes;
};

const cacheKey = (location: string, course: string, time: string, dayKey: string = getLocalDayKey()) => {
  const minutes = parseTimeToMinutes(time);
  const timePart = minutes === null ? normalize(time) : `m${minutes}`;
  return `${dayKey}|${normalize(location)}|${normalize(course)}|${timePart}`;
};

