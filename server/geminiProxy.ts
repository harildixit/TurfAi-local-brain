const parseWeightLbs = (weight: string): number | null => {
  const match = weight.match(/(\d+)\s*st\s*(\d+)\s*lb/i);
  if (!match) return null;
  const stones = Number(match[1]);
  const pounds = Number(match[2]);
  return Number.isFinite(stones) && Number.isFinite(pounds) ? stones * 14 + pounds : null;
};

const formScore = (form: string[]): number => {
  const recent = (form || []).slice(-5).reverse();
  if (recent.length === 0) return 0.35;
  const recencyWeights = [1, 0.82, 0.67, 0.55, 0.45];
  let weighted = 0;
  let weightTotal = 0;
  recent.forEach((result, index) => {
    const token = String(result || '').trim().toUpperCase();
    const parsedPosition = Number.parseInt(token, 10);
    // Racing form uses 0 for tenth or worse. Treating it as numeric zero
    // would incorrectly give an unplaced runner the maximum form score.
    const position = parsedPosition === 0 ? 10 : parsedPosition;
    const value = Number.isFinite(position) && position > 0
      ? Math.max(0, 1 - (Math.min(position, 10) - 1) / 9)
      : 0;
    const weight = recencyWeights[index] || 0.4;
    weighted += value * weight;
    weightTotal += weight;
  });
  return weightTotal > 0 ? weighted / weightTotal : 0.35;
};

const createLocalBrainPrediction = (race: Race, evidence?: PredictionEvidence | null): Prediction => {
  const runners = (race.horses || []).filter((horse) => horse?.name?.trim());
  if (runners.length === 0) throw new Error('LocalBrain requires at least one runner');

  const weights = runners.map((horse) => parseWeightLbs(horse.weight)).filter((value): value is number => value !== null);
  const minWeight = weights.length ? Math.min(...weights) : null;
  const maxWeight = weights.length ? Math.max(...weights) : null;
  const validOdds = runners
    .map((horse) => typeof horse.currentOdds === 'number' && horse.currentOdds > 1 ? horse.currentOdds : null)
    .filter((odds): odds is number => odds !== null);
  const impliedProbabilities = validOdds.map((odds) => 1 / odds);
  const minImplied = impliedProbabilities.length ? Math.min(...impliedProbabilities) : null;
  const maxImplied = impliedProbabilities.length ? Math.max(...impliedProbabilities) : null;
  const hasOdds = validOdds.length > 0;
  const hasOddsMovement = runners.some((horse) =>
    typeof horse.currentOdds === 'number' && horse.currentOdds > 1 &&
    typeof horse.openingOdds === 'number' && horse.openingOdds > 1,
  );

  const scored = runners.map((horse) => {
    const odds = typeof horse.currentOdds === 'number' && horse.currentOdds > 1 ? horse.currentOdds : null;
    const implied = odds ? 1 / odds : null;
    // Normalize market strength within this field. This preserves the
    // favourite/outsider ordering without allowing raw odds magnitudes to
    // dominate all other signals.
    const market = implied !== null && minImplied !== null && maxImplied !== null && maxImplied > minImplied
      ? (implied - minImplied) / (maxImplied - minImplied)
      : 0.5;
    const form = formScore(horse.recentForm || []);
    const lbs = parseWeightLbs(horse.weight);
    const weightScore = lbs !== null && minWeight !== null && maxWeight !== null && maxWeight > minWeight
      ? 1 - (lbs - minWeight) / (maxWeight - minWeight)
      : 0.5;
    const ageScore = horse.age > 0 ? Math.max(0.2, 1 - Math.abs(horse.age - 5) * 0.13) : 0.5;
    const drawProxy = horse.number > 0 ? 1 / Math.sqrt(horse.number) : 0.25;
    const openingOdds = typeof horse.openingOdds === 'number' && horse.openingOdds > 1 ? horse.openingOdds : null;
    const movement = openingOdds && odds ? Math.max(-1, Math.min(1, (openingOdds - odds) / openingOdds)) : 0;
    const movementScore = 0.5 + movement * 0.5;
    const score = hasOdds
      ? market * 0.55 + form * 0.25 + weightScore * 0.08 + ageScore * 0.05 + drawProxy * 0.02 + movementScore * 0.05
      : form * 0.6 + weightScore * 0.18 + ageScore * 0.12 + drawProxy * 0.1;
    return { horse, score, form, weightScore, ageScore, market, movementScore };
  }).sort((a, b) => b.score - a.score || a.horse.number - b.horse.number || a.horse.name.localeCompare(b.horse.name));

  // A softmax converts relative scores into a complete, stable probability distribution.
  const temperature = hasOdds ? 5 : 3.5;
  const maxScore = Math.max(...scored.map((item) => item.score));
  const expScores = scored.map((item) => Math.exp((item.score - maxScore) * temperature));
  const expTotal = expScores.reduce((sum, value) => sum + value, 0) || 1;
  const probabilities = scored.map((item, index) => ({
    horse: item.horse.name,
    probability: Number(((expScores[index] / expTotal) * 100).toFixed(1))
  }));
  const probabilityTotal = probabilities.reduce((sum, item) => sum + item.probability, 0);
  probabilities[0].probability = Number((probabilities[0].probability + (100 - probabilityTotal)).toFixed(1));

  const winner = scored[0];
  const formText = (winner.horse.recentForm || []).slice(-5).join('-') || 'limited recorded form';
  const evidenceText = evidence?.sentimentSummary?.trim()
    ? ' Gemini research evidence was available but the ranking remained based on structured race data.'
    : '';

  return {
    raceId: race.id,
    source: 'local-brain',
    winner: winner.horse.name,
    placed: scored.slice(1, 4).map((item) => item.horse.name),
    confidence: Math.round(probabilities[0].probability),
    reasoning: `LocalBrain ranked the field deterministically using ${hasOdds ? 'normalized market strength, ' : ''}recency-weighted form, carried weight, age profile and draw${hasOddsMovement ? ', with a small odds-movement adjustment' : ''}. ${winner.horse.name} led the score with recent form ${formText}.${evidenceText}`,
    sentimentSummary: 'Local deterministic fallback — no external prediction model was used.',
    winProbabilities: probabilities
  };
};

const createLocalGeminiHybridPrediction = (
  race: Race,
  localPrediction: Prediction,
  evidence: PredictionEvidence,
): Prediction => {
  const runners = (race.horses || []).filter((horse) => horse?.name?.trim());
  const signalByHorse = new Map(
    (evidence.runnerSignals || []).map((signal) => [normalize(signal.horse), signal]),
  );
  const covered = runners
    .map((horse) => signalByHorse.get(normalize(horse.name)))
    .filter((signal): signal is NonNullable<typeof signal> => Boolean(signal));

  // Do not let a partial or low-confidence search response move the ranking
  // materially. At least 60% of the field must be covered before Gemini is
  // allowed into the blend.
  const minimumCoverage = Math.max(2, Math.ceil(runners.length * 0.6));
  if (covered.length < minimumCoverage) return localPrediction;

  const averageConfidence = covered.reduce((sum, signal) => sum + signal.confidence, 0) / covered.length;
  const coverage = covered.length / runners.length;
  const evidenceQuality = Math.max(0, Math.min(1, coverage * (averageConfidence / 100)));
  const geminiWeight = Math.min(0.25, 0.25 * evidenceQuality);
  if (geminiWeight <= 0) return localPrediction;

  const localProbabilities = new Map(
    (localPrediction.winProbabilities || []).map((item) => [normalize(item.horse), item.probability]),
  );
  const rawGeminiScores = runners.map((horse) => {
    const signal = signalByHorse.get(normalize(horse.name));
    // A runner without useful research remains neutral rather than receiving
    // an artificial boost or penalty.
    return signal ? signal.score : 50;
  });
  const maxGeminiScore = Math.max(...rawGeminiScores);
  const geminiExpScores = rawGeminiScores.map((score) => Math.exp((score - maxGeminiScore) / 20));
  const geminiTotal = geminiExpScores.reduce((sum, score) => sum + score, 0) || 1;

  const blended = runners.map((horse, index) => {
    const localProbability = localProbabilities.get(normalize(horse.name)) || 0;
    const geminiProbability = (geminiExpScores[index] / geminiTotal) * 100;
    return {
      horse,
      probability: localProbability * (1 - geminiWeight) + geminiProbability * geminiWeight,
    };
  });

  const probabilityTotal = blended.reduce((sum, item) => sum + item.probability, 0) || 1;
  const ranked = blended
    .map((item) => ({ ...item, probability: (item.probability / probabilityTotal) * 100 }))
    .sort((a, b) => b.probability - a.probability || a.horse.number - b.horse.number || a.horse.name.localeCompare(b.horse.name));

  const probabilities = ranked.map((item) => ({
    horse: item.horse.name,
    probability: Number(item.probability.toFixed(1)),
  }));
  const roundedTotal = probabilities.reduce((sum, item) => sum + item.probability, 0);
  probabilities[0].probability = Number((probabilities[0].probability + (100 - roundedTotal)).toFixed(1));

  const winner = ranked[0];
  const secondProbability = ranked[1]?.probability || 0;
  const confidence = Math.round(Math.min(99, winner.probability + Math.max(0, winner.probability - secondProbability) * 0.5));
  const winnerSignal = signalByHorse.get(normalize(winner.horse.name));
  const note = winnerSignal?.note ? ` Gemini's runner note: ${winnerSignal.note}` : '';
  const localShare = Math.round((1 - geminiWeight) * 100);
  const geminiShare = Math.round(geminiWeight * 100);

  return {
    raceId: race.id,
    source: 'hybrid',
    winner: winner.horse.name,
    placed: ranked.slice(1, 4).map((item) => item.horse.name),
    confidence,
    reasoning: `Hybrid ranking blended LocalBrain structured scoring (${localShare}%) with Gemini's grounded runner evidence (${geminiShare}%, ${covered.length}/${runners.length} runners covered). ${winner.horse.name} led the blended probability distribution.${note}`,
    sentimentSummary: evidence.sentimentSummary || 'Gemini research evidence was unavailable for this race.',
    winProbabilities: probabilities,
  };
};

const fetchPredictionFromAI = async (race: Race): Promise<Prediction> => {
  const localPrediction = createLocalBrainPrediction(race);
  if (!isLocalGeminiHybridEnabled()) return localPrediction;
  if (isLocalGeminiHybridEnabled()) {
    try {
      console.log(`[Hybrid] Analyzing race with LocalBrain + Gemini evidence: ${race.course} at ${race.time}`);
      const evidence = await fetchPredictionEvidenceFromGeminiFlash(race);
      return createLocalGeminiHybridPrediction(race, localPrediction, evidence);
    } catch (e) {
      console.log(`[LocalBrain] Gemini evidence unavailable for ${race.course} at ${race.time}; using deterministic ranking ${summarizeGeminiError(e)}`);
      return localPrediction;
    }
  }

  return localPrediction;
};

