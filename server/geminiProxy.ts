const serializeMap = <T>(map: Map<string, T>) => Array.from(map.entries());
const hydrateMap = <T>(entries: Array<[string, T]>, map: Map<string, T>) => {
  map.clear();
  for (const [k, v] of entries) map.set(k, v);
};

const loadDb = async () => {
  if (dbLoaded) return;
  if (dbLoadInFlight) return dbLoadInFlight;
  dbLoadInFlight = (async () => {
    try {
      const raw = await fs.readFile(dbPath, 'utf8');
      const parsed = JSON.parse(raw) as {
        dayKey?: string;
        scheduleByLocation?: Array<[string, Cached<Race[]>]>;
        cardByRaceKey?: Array<[string, Cached<RaceCard>]>;
        predictionByRaceKey?: Array<[string, Cached<Prediction>]>;
        resultByRaceKey?: Array<[string, Cached<StoredResult>]>;
        historyByRaceKey?: Array<[string, Cached<StoredHistory>]>;
        fetchCountByRaceKey?: Array<[string, number]>;
      };

      const currentDayKey = getLocalDayKey();
      const isSameDay = parsed.dayKey === currentDayKey;

      if (isSameDay) {
        if (parsed.scheduleByLocation) hydrateMap(parsed.scheduleByLocation, state.scheduleByLocation);
        if (parsed.cardByRaceKey) {
          hydrateMap(
            parsed.cardByRaceKey.map(([key, cached]) => [
              key,
              { ...cached, value: normalizeRaceCardOdds(cached.value) },
            ]),
            state.cardByRaceKey,
          );
        }
        if (parsed.predictionByRaceKey) {
          const predictions = isLocalPredictionSandbox()
            ? parsed.predictionByRaceKey.filter(([, cached]) => cached.value.source === 'local-brain' || cached.value.source === 'hybrid')
            : parsed.predictionByRaceKey;
          hydrateMap(predictions, state.predictionByRaceKey);
        }
        if (parsed.resultByRaceKey) hydrateMap(parsed.resultByRaceKey, state.resultByRaceKey);
        if (parsed.fetchCountByRaceKey) hydrateMap(parsed.fetchCountByRaceKey, state.fetchCountByRaceKey);
      }

      // Always load history to preserve past performance data
      if (parsed.historyByRaceKey) hydrateMap(parsed.historyByRaceKey, state.historyByRaceKey);
    } catch {
      return;
    }
  })()
    .finally(() => {
      dbLoaded = true;
      dbLoadInFlight = null;
    });
  return dbLoadInFlight;
};

const writeDbNow = async () => {
  if (dbWriteInFlight) return dbWriteInFlight;
  dbWriteInFlight = (async () => {
    const payload = {
      dayKey: getLocalDayKey(),
      scheduleByLocation: serializeMap(state.scheduleByLocation),
      cardByRaceKey: serializeMap(state.cardByRaceKey),
      predictionByRaceKey: serializeMap(state.predictionByRaceKey),
      resultByRaceKey: serializeMap(state.resultByRaceKey),
      historyByRaceKey: serializeMap(state.historyByRaceKey),
      fetchCountByRaceKey: serializeMap(state.fetchCountByRaceKey),
    };

    const tmpPath = `${dbPath}.tmp`;
    try {
      await fs.writeFile(tmpPath, JSON.stringify(payload), 'utf8');
      await fs.rename(tmpPath, dbPath);
    } catch (e) {
      // ignore write errors to prevent crash
    }
  })().finally(() => {
    dbWriteInFlight = null;
  });
  return dbWriteInFlight;
};

const scheduleDbWrite = () => {
  if (dbWriteTimer) clearTimeout(dbWriteTimer);
  dbWriteTimer = setTimeout(() => {
    void writeDbNow();
  }, 250);
};

type FirestoreScheduleWrite = { dayKey: string; location: string; updatedAt: number; races: Race[]; source: 'racing-api' };
type FirestoreRaceWrite = {
  dayKey: string;
  location: string;
  course: string;
  time: string;
  patch: Record<string, unknown>;
};

const firestorePending = {
  schedules: new Map<string, FirestoreScheduleWrite>(),
  races: new Map<string, FirestoreRaceWrite>()
};

let firestoreWriteTimer: NodeJS.Timeout | undefined;
let firestoreWriteInFlight: Promise<void> | null = null;

const scheduleFirestoreWrite = () => {
  if (firestoreWritesDisabled() || !isFirestoreEnabled()) return;
  console.log('Scheduling Firestore write...');
  if (firestoreWriteTimer) clearTimeout(firestoreWriteTimer);
  firestoreWriteTimer = setTimeout(() => {
    void flushFirestoreWrites();
  }, 500);
};

const stripScheduleRaces = (races: Race[]) => {
  return races.map((r) => ({ ...r, horses: [] }));
};

const flushFirestoreWrites = async () => {
  if (firestoreWritesDisabled()) return;
  if (firestoreWriteInFlight) return firestoreWriteInFlight;
  const db = getFirestoreDb();
  if (!db) return;

  const schedules = Array.from(firestorePending.schedules.values());
  const races = Array.from(firestorePending.races.values());
  firestorePending.schedules.clear();
  firestorePending.races.clear();

  const writes = async () => {
    console.log(`Flushing ${schedules.length} schedules and ${races.length} races to Firestore...`);
    const locIdCache = new Map<string, string>();
    const getLocId = async (dayKey: string, location: string) => {
      const cacheId = `${dayKey}|${normalize(location)}`;
      const existing = locIdCache.get(cacheId);
      if (existing) return existing;
      const resolved = await resolveFirestoreLocationId(db, dayKey, location);
      locIdCache.set(cacheId, resolved);
      return resolved;
    };

    const allOps: Array<{
      ref: any;
      data: Record<string, unknown>;
    }> = [];

    for (const s of schedules) {
      const locId = await getLocId(s.dayKey, s.location);
      allOps.push({
        ref: getFirestoreScheduleDocById(db, s.dayKey, locId),
        data: {
          dayKey: s.dayKey,
          location: s.location,
          locationNormalized: normalize(s.location),
          races: stripScheduleRaces(s.races),
          updatedAt: s.updatedAt,
          source: s.source
        }
      });
    }

    for (const r of races) {
      const locId = await getLocId(r.dayKey, r.location);
      const raceDocId = encodeURIComponent(cacheKey(r.location, r.course, r.time, r.dayKey));
      allOps.push({
        ref: getFirestoreRaceDocById(db, r.dayKey, locId, raceDocId),
        data: {
          dayKey: r.dayKey,
          location: r.location,
          locationNormalized: normalize(r.location),
          course: r.course,
          courseNormalized: normalize(r.course),
          time: r.time,
          key: cacheKey(r.location, r.course, r.time, r.dayKey),
          ...r.patch
        }
      });
    }

    const chunkSize = 450;
    for (let i = 0; i < allOps.length; i += chunkSize) {
      const batch = db.batch();
      for (const op of allOps.slice(i, i + chunkSize)) {
        batch.set(op.ref, op.data, { merge: true });
      }
      await batch.commit();
    }
    console.log('Firestore flush successful.');
  };

  firestoreWriteInFlight = writes()
    .catch((err) => {
      console.error('Firestore flush failed:', err);
      for (const s of schedules) firestorePending.schedules.set(`${s.dayKey}|${normalize(s.location)}`, s);
      for (const r of races) firestorePending.races.set(cacheKey(r.location, r.course, r.time, r.dayKey), r);
      scheduleFirestoreWrite();
    })
    .finally(() => {
      firestoreWriteInFlight = null;
    });

  return firestoreWriteInFlight;
};

const queueFirestoreScheduleWrite = (location: string, cached: Cached<Race[]>) => {
  if (!isFirestoreEnabled()) return;
  firestorePending.schedules.set(`${cached.dayKey}|${normalize(location)}`, {
    dayKey: cached.dayKey,
    location,
    updatedAt: cached.updatedAt,
    races: cached.value,
    source: 'racing-api'
  });
  scheduleFirestoreWrite();
};

const queueFirestoreRacePatch = (location: string, course: string, time: string, dayKey: string, patch: Record<string, unknown>) => {
  if (!isFirestoreEnabled()) return;
  const key = cacheKey(location, course, time, dayKey);
  const existing = firestorePending.races.get(key);
  firestorePending.races.set(key, {
    dayKey,
    location,
    course,
    time,
    patch: { ...(existing?.patch || {}), ...patch }
  });
  scheduleFirestoreWrite();
};

const storeSchedule = (location: string, races: Race[], updatedAt: number, dayKey: string, replicate: boolean) => {
  const cacheId = `${dayKey}|${normalize(location)}`;
  state.scheduleByLocation.set(cacheId, { value: races, updatedAt, dayKey, source: 'racing-api' });
  scheduleDbWrite();
  if (replicate) queueFirestoreScheduleWrite(location, { value: races, updatedAt, dayKey });
};

