const getFirestoreDb = () => {
  if (firestoreDb !== undefined) return firestoreDb;
  if (!isFirestoreEnabled()) {
    firestoreDb = null;
    return null;
  }

  try {
    const mode = (process.env.NODE_ENV || '').trim().toLowerCase();
    const isDev = mode !== 'production';
    const restConfig = firestoreRestConfig();
    const hasExplicitCredential = Boolean(
      (process.env.FIREBASE_SERVICE_ACCOUNT_JSON || process.env.FIRESTORE_SERVICE_ACCOUNT_JSON || '').trim() ||
      (process.env.FIREBASE_SERVICE_ACCOUNT_BASE64 || process.env.FIRESTORE_SERVICE_ACCOUNT_BASE64 || '').trim() ||
      (process.env.GOOGLE_APPLICATION_CREDENTIALS || '').trim()
    );
    if (isDev && restConfig && !hasExplicitCredential) {
      // The local process has the public Firebase web config, but not a
      // service-account/ADC credential. Use the read-only REST fallback below.
      firestoreDb = null;
      return null;
    }
    if (getApps().length === 0) {
      const projectId =
        (process.env.FIREBASE_PROJECT_ID ||
          process.env.VITE_FIREBASE_PROJECT_ID ||
          process.env.GCLOUD_PROJECT ||
          process.env.GOOGLE_CLOUD_PROJECT ||
          '').trim() || undefined;

      const serviceAccountJson =
        (process.env.FIREBASE_SERVICE_ACCOUNT_JSON || process.env.FIRESTORE_SERVICE_ACCOUNT_JSON || '').trim();

      const serviceAccountBase64 =
        (process.env.FIREBASE_SERVICE_ACCOUNT_BASE64 || process.env.FIRESTORE_SERVICE_ACCOUNT_BASE64 || '').trim();

      const credential = serviceAccountJson
        ? cert(JSON.parse(serviceAccountJson))
        : serviceAccountBase64
          ? cert(JSON.parse(Buffer.from(serviceAccountBase64, 'base64').toString('utf8')))
          : applicationDefault();

      initializeApp(projectId ? { credential, projectId } : { credential });
    }
    firestoreDb = readOnlyFirestore(getAdminFirestore());
    console.log('Firestore initialized successfully.');
    return firestoreDb;
  } catch (e) {
    const mode = (process.env.NODE_ENV || '').trim().toLowerCase();
    const isDev = mode !== 'production';
    if (isDev && !firestoreRestConfig()) {
      const message = e instanceof Error ? e.message : 'Unknown error';
      throw new Error(`Failed to init Firestore in dev: ${message}`);
    }
    // Local development can still read the public Firestore cache through the
    // REST API when Admin SDK credentials are not installed. Production keeps
    // using the Admin SDK for reads and writes.
    firestoreDb = null;
    return null;
  }
};

