const decodeFirestoreRestValue = (value: FirestoreRestValue | undefined): unknown => {
  if (!value) return undefined;
  if ('nullValue' in value) return null;
  if ('booleanValue' in value) return value.booleanValue;
  if ('integerValue' in value) return Number(value.integerValue);
  if ('doubleValue' in value) return value.doubleValue;
  if ('timestampValue' in value) return value.timestampValue;
  if ('stringValue' in value) return value.stringValue;
  if ('arrayValue' in value) return (value.arrayValue?.values || []).map(decodeFirestoreRestValue);
  if ('mapValue' in value) return Object.fromEntries(
    Object.entries(value.mapValue?.fields || {}).map(([key, nested]) => [key, decodeFirestoreRestValue(nested)])
  );
  return undefined;
};

const decodeFirestoreRestFields = (fields: Record<string, FirestoreRestValue> | undefined) => {
  return Object.fromEntries(
    Object.entries(fields || {}).map(([key, value]) => [key, decodeFirestoreRestValue(value)])
  );
};

const firestoreRestRequest = async (segments: string[]) => {
  const config = firestoreRestConfig();
  if (!config) return null;
  const path = segments.map((segment) => encodeURIComponent(segment)).join('/');
  const url = `https://firestore.googleapis.com/v1/projects/${encodeURIComponent(config.projectId)}/databases/(default)/documents/${path}?key=${encodeURIComponent(config.apiKey)}`;
  const response = await fetch(url);
  if (response.status === 404) return null;
  if (!response.ok) throw new Error(`Firestore REST request failed: HTTP ${response.status}`);
  return await response.json() as { fields?: Record<string, FirestoreRestValue>; documents?: Array<{ fields?: Record<string, FirestoreRestValue> }> };
};

const readFirestoreRestDocument = async (segments: string[]) => {
  const document = await firestoreRestRequest(segments);
  return document ? decodeFirestoreRestFields(document.fields) : null;
};

const readFirestoreRestCollection = async (segments: string[]) => {
  const response = await firestoreRestRequest(segments);
  return (response?.documents || []).map((document) => decodeFirestoreRestFields(document.fields));
};

