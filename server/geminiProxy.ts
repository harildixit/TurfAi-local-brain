const secretsMatch = (provided: string, expected: string) => {
  const providedBuffer = Buffer.from(provided);
  const expectedBuffer = Buffer.from(expected);
  return providedBuffer.length === expectedBuffer.length && timingSafeEqual(providedBuffer, expectedBuffer);
};

const isCronAuthorized = (req: any) => {
  const secret = getCronSecret();
  if (!secret) return false;
  const authorization = (getHeader(req, 'authorization') || '').trim();
  const bearer = authorization.toLowerCase().startsWith('bearer ')
    ? authorization.slice(7).trim()
    : '';
  const token = (
    getHeader(req, 'x-internal-token') ||
    getHeader(req, 'x-cron-secret') ||
    bearer
  ).trim();
  return Boolean(token) && secretsMatch(token, secret);
};

