const firestoreResolvedLocationIds = new Map<string, string>();

const resolveFirestoreLocationId = async (db: Firestore, dayKey: string, location: string) => {
  const cacheId = `${dayKey}|${normalize(location)}`;
  const cached = firestoreResolvedLocationIds.get(cacheId);
  if (cached) return cached;

  const candidates = firestoreLocationIdCandidates(location);
  for (const locId of candidates) {
    try {
      const snap = await getFirestoreScheduleDocById(db, dayKey, locId).get();
      if (snap.exists) {
        firestoreResolvedLocationIds.set(cacheId, locId);
        return locId;
      }
    } catch {
      // ignore
    }
  }

  const fallback = candidates[0] || encodeURIComponent(normalize(location));
  firestoreResolvedLocationIds.set(cacheId, fallback);
  return fallback;
};

