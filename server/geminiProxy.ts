const getOrFetchSchedule = async (location: string, force: boolean, replicate: boolean, requestedDayKey = getLocalDayKey()) => {
  const dayKey = requestedDayKey;
  const isHistoricalDay = dayKey !== getLocalDayKey();
  const cacheId = `${dayKey}|${normalize(location)}`;
  const cached = state.scheduleByLocation.get(cacheId);

  // Historical dates are read-only. Never fall back to the live Racing API for
  // them, because that would show today's races under a past date.
  if (isHistoricalDay) {
    if (cached?.source === 'racing-api' && cached.dayKey === dayKey) return normalizeSchedule(cached.value);
    const fromFirestore = await readScheduleFromFirestore(location, dayKey);
    if (fromFirestore?.source === 'racing-api') {
      storeSchedule(location, fromFirestore.value, fromFirestore.updatedAt, dayKey, false);
      return fromFirestore.value;
    }
    throw new Error(`No stored race schedule for ${dayKey}`);
  }

  if (!force && cached?.source === 'racing-api' && isFresh(cached, scheduleTtlMs)) {
    const normalized = normalizeSchedule(cached.value);
    if (normalized.some((r, i) => r.id !== cached.value[i]?.id)) {
      storeSchedule(location, normalized, cached.updatedAt, dayKey, replicate);
    }
    return normalized;
  }

  if (!force) {
    const fromFirestore = await readScheduleFromFirestore(location, dayKey);
    // Firestore is a persistence cache, not the source of truth. Refresh it
    // when its schedule is older than the API cache window so corrected race
    // times (such as an evening `off_dt`) reach the frontend.
    if (fromFirestore?.source === 'racing-api' && isFresh(fromFirestore, scheduleTtlMs)) {
      storeSchedule(location, fromFirestore.value, fromFirestore.updatedAt, fromFirestore.dayKey, false);
      return fromFirestore.value;
    }
  }

  try {
    const races = normalizeSchedule(await fetchScheduleFromRacingApi(location));
    if (races.length === 0) throw new Error('No schedule found');
    storeSchedule(location, races, now(), dayKey, replicate);
    return races;
  } catch (e) {
    if (cached && cached.dayKey === dayKey && cached.source === 'racing-api') return normalizeSchedule(cached.value);
    throw e;
  }
};

