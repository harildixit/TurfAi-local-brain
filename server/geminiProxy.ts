const seedFirestoreFromLocalCache = async (location: string, dayKey: string) => {
  if (!isFirestoreEnabled()) return 0;
  const db = getFirestoreDb();
  if (!db) return 0;

  const cacheId = `${dayKey}|${normalize(location)}`;
  const schedule = state.scheduleByLocation.get(cacheId);
  if (!schedule || schedule.dayKey !== dayKey || schedule.source !== 'racing-api') return 0;

  queueFirestoreScheduleWrite(location, schedule);
  let queued = 1;

  for (const race of schedule.value) {
    const key = cacheKey(location, race.course, race.time, dayKey);

    const card = state.cardByRaceKey.get(key);
    if (card && card.dayKey === dayKey && card.source === 'racing-api' && hasRunners(card.value)) {
      queueFirestoreRacePatch(location, race.course, race.time, dayKey, {
        card: card.value,
        cardUpdatedAt: card.updatedAt,
        cardSource: 'racing-api'
      });
      queued++;
    }

    const prediction = state.predictionByRaceKey.get(key);
    if (prediction && prediction.dayKey === dayKey) {
      queueFirestoreRacePatch(location, race.course, race.time, dayKey, {
        prediction: prediction.value,
        predictionUpdatedAt: prediction.updatedAt
      });
      queued++;
    }

    const result = state.resultByRaceKey.get(key);
    if (result && result.dayKey === dayKey) {
      queueFirestoreRacePatch(location, race.course, race.time, dayKey, { result: result.value, resultUpdatedAt: result.updatedAt });
      queued++;
    }

    const history = state.historyByRaceKey.get(key);
    if (history && history.dayKey === dayKey) {
      queueFirestoreRacePatch(location, race.course, race.time, dayKey, {
        history: history.value,
        historyUpdatedAt: history.updatedAt
      });
      queued++;
    }
  }

  await flushFirestoreWrites();
  return queued;
};

const readScheduleFromFirestore = async (location: string, dayKey: string) => {
  const db = getFirestoreDb();
  if (!db) {
    try {
      const candidates = firestoreLocationIdCandidates(location);
      for (const locId of candidates) {
        const data = await readFirestoreRestDocument([
          getFirestoreCollectionName(), dayKey, 'locations', locId, 'schedule', 'current'
        ]);
        const races = Array.isArray(data?.races) ? data.races as Race[] : null;
        if (!races || data?.source !== 'racing-api') continue;
        firestoreResolvedLocationIds.set(`${dayKey}|${normalize(location)}`, locId);
        return {
          value: normalizeSchedule(races),
          updatedAt: typeof data.updatedAt === 'number' ? data.updatedAt : now(),
          dayKey,
          source: 'racing-api'
        } satisfies Cached<Race[]>;
      }
      return null;
    } catch {
      return null;
    }
  }
  try {
    const candidates = firestoreLocationIdCandidates(location);
    for (const locId of candidates) {
      let doc: any;
      try {
        doc = await getFirestoreScheduleDocById(db, dayKey, locId).get();
      } catch {
        continue;
      }
      if (!doc?.exists) continue;
      firestoreResolvedLocationIds.set(`${dayKey}|${normalize(location)}`, locId);

      const data = doc.data() as any;
      const races = Array.isArray(data?.races) ? (data.races as Race[]) : null;
      if (!races) continue;
      // Only Racing API schedules are valid. Older documents without a source
      // marker are deliberately ignored so legacy Gemini data cannot reappear.
      if (data?.source !== 'racing-api') continue;
      const updatedAt = typeof data?.updatedAt === 'number' ? data.updatedAt : now();
      return { value: normalizeSchedule(races), updatedAt, dayKey, source: 'racing-api' } satisfies Cached<Race[]>;
    }

    // Older archived days may have race documents (cards/results/predictions)
    // but no schedule summary. Rebuild the fixture list from those documents
    // so historical pages remain browseable without touching the live API.
    for (const locId of candidates) {
      let snap: any;
      try {
        snap = await getFirestoreLocationDocById(db, dayKey, locId).collection('races').get();
      } catch {
        continue;
      }

      const races = snap.docs.map((raceDoc: any) => {
        const data = raceDoc.data() as any;
        const card = data?.card as Partial<Race> | undefined;
        const history = data?.history as Partial<HistoricalRecord> | undefined;
        const result = data?.result as StoredResult | undefined;
        const course = String(data?.course || '').trim();
        const time = String(data?.time || '').trim();
        if (!course || !time) return null;
        if (data?.dayKey && data.dayKey !== dayKey) return null;
        if (data?.cardSource !== 'racing-api' && !history?.actualWinner && !result?.winner) return null;

        return {
          id: `${course}-${time}`,
          course,
          time,
          name: card?.name || '',
          class: card?.class || '',
          distance: card?.distance || history?.distance || '',
          going: card?.going || history?.going || '',
          weather: card?.weather || history?.weather || '',
          horses: Array.isArray(card?.horses) ? card.horses : [],
          status: card?.status || (result?.winner && result.winner !== 'PENDING' ? 'finished' : 'scheduled'),
          result: result && result.winner && result.winner !== 'PENDING'
            ? { winner: result.winner, placed: result.placed || [] }
            : undefined,
        } as Race;
      }).filter((race: Race | null): race is Race => Boolean(race));

      if (races.length > 0) {
        firestoreResolvedLocationIds.set(`${dayKey}|${normalize(location)}`, locId);
        return { value: normalizeSchedule(races), updatedAt: now(), dayKey, source: 'racing-api' } satisfies Cached<Race[]>;
      }
    }
    return null;
  } catch {
    if (firestoreRestConfig()) {
      firestoreDb = null;
      return readScheduleFromFirestore(location, dayKey);
    }
    return null;
  }
};

const hydrateRacesFromFirestore = async (location: string, races: Race[], dayKey: string) => {
  const db = getFirestoreDb();
  if (!db) {
    try {
      const locId = firestoreResolvedLocationIds.get(`${dayKey}|${normalize(location)}`) || firestoreLocationIdCandidates(location)[0];
      const documents = await readFirestoreRestCollection([
        getFirestoreCollectionName(), dayKey, 'locations', locId, 'races'
      ]);
      let loaded = 0;
      for (const race of races) {
        const data = documents.find((candidate: any) =>
          normalize(String(candidate?.course || '')) === normalize(race.course) &&
          (normalize(String(candidate?.time || '')) === normalize(race.time) ||
            parseTimeToMinutes(String(candidate?.time || '')) === parseTimeToMinutes(race.time))
        ) as any;
        if (!data) continue;

        const key = cacheKey(location, race.course, race.time, dayKey);
        const card = data.card as RaceCard | undefined;
        if (card && data.cardSource === 'racing-api' && hasRunners(card)) {
          const updatedAt = typeof data.cardUpdatedAt === 'number' ? data.cardUpdatedAt : now();
          state.cardByRaceKey.set(key, { value: normalizeRaceCardOdds(card), updatedAt, dayKey, source: 'racing-api' });
          loaded++;
        }

        const prediction = data.prediction as Prediction | undefined;
        if (prediction && isValidPrediction(prediction) && !isLocalPredictionSandbox()) {
          const updatedAt = typeof data.predictionUpdatedAt === 'number' ? data.predictionUpdatedAt : now();
          state.predictionByRaceKey.set(key, { value: prediction, updatedAt, dayKey });
          loaded++;
        }

        const result = data.result as StoredResult | undefined;
        if (result) {
          const updatedAt = typeof data.resultUpdatedAt === 'number' ? data.resultUpdatedAt : now();
          state.resultByRaceKey.set(key, { value: result, updatedAt, dayKey });
          loaded++;
        }

        const history = data.history as StoredHistory | undefined;
        if (history) {
          const updatedAt = typeof data.historyUpdatedAt === 'number' ? data.historyUpdatedAt : now();
          state.historyByRaceKey.set(key, { value: history, updatedAt, dayKey });
          loaded++;
        }
      }
      if (loaded > 0) scheduleDbWrite();
      return loaded;
    } catch {
      return 0;
    }
  }

  const toFetch = races.filter((r) => {
    const key = cacheKey(location, r.course, r.time, dayKey);
    const card = state.cardByRaceKey.get(key);
    const prediction = state.predictionByRaceKey.get(key);
    const result = state.resultByRaceKey.get(key);
    const history = state.historyByRaceKey.get(key);

    const missingCard = !(card && card.dayKey === dayKey && card.source === 'racing-api' && hasRunners(card.value));
    const missingPrediction = !(prediction && prediction.dayKey === dayKey);
    const missingResult = !(result && result.dayKey === dayKey);
    const missingHistory = !(history && history.dayKey === dayKey);

    return missingCard || missingPrediction || missingResult || missingHistory;
  });
  if (toFetch.length === 0) return 0;

  let locId: string;
  try {
    locId = await resolveFirestoreLocationId(db, dayKey, location);
  } catch {
    return 0;
  }

  const idCandidatesByRace = toFetch.map((r) => firestoreRaceDocIdCandidates(dayKey, location, r.course, r.time));
  const refs = idCandidatesByRace.flatMap((ids) => ids.map((docId) => getFirestoreRaceDocById(db, dayKey, locId, docId)));

  let docs: any[] = [];
  try {
    docs = await (db as any).getAll(...refs);
  } catch {
    if (firestoreRestConfig()) {
      firestoreDb = null;
      return hydrateRacesFromFirestore(location, races, dayKey);
    }
    return 0;
  }

  let loaded = 0;
  let cursor = 0;
  for (let i = 0; i < toFetch.length; i++) {
    const ids = idCandidatesByRace[i];
    let snap: any | null = null;
    for (let j = 0; j < ids.length; j++) {
      const candidate = docs[cursor + j];
      if (candidate?.exists) {
        snap = candidate;
        break;
      }
    }
    cursor += ids.length;
    if (!snap?.exists) continue;

    const data = snap.data() as any;
    const course = (data?.course || toFetch[i].course || '').trim();
    const time = (data?.time || toFetch[i].time || '').trim();
    const key = cacheKey(location, course, time, dayKey);

    const card = data?.card as RaceCard | undefined;
    if (card && data?.cardSource === 'racing-api' && hasRunners(card)) {
      const updatedAt = typeof data?.cardUpdatedAt === 'number' ? data.cardUpdatedAt : now();
      state.cardByRaceKey.set(key, { value: normalizeRaceCardOdds(card), updatedAt, dayKey, source: 'racing-api' });
      loaded++;
    }

    const prediction = data?.prediction as Prediction | undefined;
    if (prediction && isValidPrediction(prediction) && !isLocalPredictionSandbox()) {
      const updatedAt = typeof data?.predictionUpdatedAt === 'number' ? data.predictionUpdatedAt : now();
      state.predictionByRaceKey.set(key, { value: prediction, updatedAt, dayKey });
      loaded++;
    }

    const result = data?.result as StoredResult | undefined;
    if (result) {
      const updatedAt = typeof data?.resultUpdatedAt === 'number' ? data.resultUpdatedAt : now();
      state.resultByRaceKey.set(key, { value: result, updatedAt, dayKey });
      loaded++;
    }

    const history = data?.history as StoredHistory | undefined;
    if (history) {
      const updatedAt = typeof data?.historyUpdatedAt === 'number' ? data.historyUpdatedAt : now();
      state.historyByRaceKey.set(key, { value: history, updatedAt, dayKey });
      loaded++;
    }
  }

  if (loaded > 0) scheduleDbWrite();
  return loaded;
};

const hydrateHistoryFromFirestore = async (location: string, dayKey: string) => {
  const db = getFirestoreDb();
  if (!db) {
    try {
      const locId = firestoreResolvedLocationIds.get(`${dayKey}|${normalize(location)}`) || firestoreLocationIdCandidates(location)[0];
      const documents = await readFirestoreRestCollection([
        getFirestoreCollectionName(), dayKey, 'locations', locId, 'races'
      ]);
      let loaded = 0;
      for (const data of documents) {
        const course = String(data?.course || '').trim();
        const time = String(data?.time || '').trim();
        if (!course || !time) continue;
        const key = cacheKey(location, course, time, dayKey);
        const history = data?.history as StoredHistory | undefined;
        if (history) {
          const updatedAt = typeof data.historyUpdatedAt === 'number' ? data.historyUpdatedAt : now();
          state.historyByRaceKey.set(key, { value: history, updatedAt, dayKey });
          loaded++;
        }
        const prediction = data?.prediction as Prediction | undefined;
        if (prediction && !isLocalPredictionSandbox()) {
          const updatedAt = typeof data.predictionUpdatedAt === 'number' ? data.predictionUpdatedAt : now();
          state.predictionByRaceKey.set(key, { value: prediction, updatedAt, dayKey });
          loaded++;
        }
      }
      if (loaded > 0) scheduleDbWrite();
      return loaded;
    } catch {
      return 0;
    }
  }

  let loaded = 0;
  try {
    const locId = await resolveFirestoreLocationId(db, dayKey, location);
    const snap = await getFirestoreLocationDocById(db, dayKey, locId).collection('races').get();
    for (const doc of snap.docs) {
      const data = doc.data() as any;
      const course = (data?.course || '').trim();
      const time = (data?.time || '').trim();
      if (!course || !time) continue;
      const key = cacheKey(location, course, time, dayKey);
      
      const history = data?.history as StoredHistory | undefined;
      if (history) {
        const updatedAt = typeof data?.historyUpdatedAt === 'number' ? data.historyUpdatedAt : now();
        state.historyByRaceKey.set(key, { value: history, updatedAt, dayKey });
        loaded++;
      }

      // Also hydrate predictions to ensure backfill works for historic data
      const prediction = data?.prediction as Prediction | undefined;
      if (prediction && !isLocalPredictionSandbox()) {
        const updatedAt = typeof data?.predictionUpdatedAt === 'number' ? data.predictionUpdatedAt : now();
        state.predictionByRaceKey.set(key, { value: prediction, updatedAt, dayKey });
        loaded++;
      }
    }
  } catch {
    if (firestoreRestConfig()) {
      firestoreDb = null;
      return hydrateHistoryFromFirestore(location, dayKey);
    }
    return 0;
  }

  if (loaded > 0) scheduleDbWrite();
  return loaded;
};

const getEnrichedSchedule = (location: string, races: Race[], includeCachedCard = true, dayKey = getLocalDayKey()) => {
  return races.map((race) => {
    const key = cacheKey(location, race.course, race.time, dayKey);
    let enriched = { ...race };
    
    const card = state.cardByRaceKey.get(key);
    if (includeCachedCard && card && card.source === 'racing-api' && card.dayKey === dayKey) {
      enriched = { ...enriched, ...card.value };
    }

    const count = state.fetchCountByRaceKey.get(key) || 0;
    enriched.fetchCount = count;

    const result = state.resultByRaceKey.get(key);
    if (result && result.dayKey === dayKey && result.value.winner !== 'PENDING') {
      enriched.result = {
        winner: result.value.winner,
        placed: result.value.placed,
        fetchCount: count
      };
    }

    return enriched;
  });
};

