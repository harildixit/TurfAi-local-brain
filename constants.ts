export const getCardImage = (id: string) => {
  // Check if the id is a known course name first
  const normalizedId = id.split('-')[0].trim(); // Extract course from "Course-Time"
  
  // Direct match in COURSE_IMAGES
  if (COURSE_IMAGES[normalizedId]) {
    return COURSE_IMAGES[normalizedId];
  }
  
  // Fallback to hashing for random but consistent image from the full list
  const charCode = id.split('').reduce((acc, char) => acc + char.charCodeAt(0), 0);
  return ALL_IMAGES[charCode % ALL_IMAGES.length];
};
